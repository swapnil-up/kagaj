"""Flatten the committed observation JSON into tidy, hostname-first CSVs.

The dataset grain is one row per hostname per observation, not one row per
local level: a hostname can belong to an office that the roster does not
contain, and attribution is a separate, evidence-bearing join.

Every artifact is written deterministically and fingerprinted in ``build.json``
so ``python -m kagaj_core.manifest validate`` can detect a stale build.
"""

from __future__ import annotations

import csv
import gzip
import hashlib
import io
import json
import subprocess
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterable
from urllib.parse import urlparse

from . import paths

DATASET_DIR = paths.DATASET_DIR
OBSERVATION_DIR = paths.OBSERVATION_DIR
SOURCE_DIR = paths.SOURCE_DIR

HEADER_NAMES = (
    "Content-Security-Policy",
    "Strict-Transport-Security",
    "X-Content-Type-Options",
    "X-Frame-Options",
    "Referrer-Policy",
    "Permissions-Policy",
)
HEADER_COLUMNS = {name: "has_" + name.lower().replace("-", "_") for name in HEADER_NAMES}

# Raw inputs are committed alongside the derived tables: a network observation
# cannot be regenerated byte-for-byte, so the JSON is the evidence.
RAW_ARTIFACTS = (
    "roster.json",
    "roster_meta.json",
    "roster_adjudication.json",
    "attribution.json",
    "attribution_overrides.json",
    "tls_sample.json",
    "website_coverage_crtsh.json",
    "website_mappings_crtsh.json",
    "sources/crtsh_gov_np.json",
    "sources/wikidata_nepal_websites.json",
    "sources/localbody_directory.json",
    "sources/osm_np_local_levels.json",
    "observations/http_header_observations.json",
    "observations/hosting_observations.json",
    "observations/dns_mail_observations.json",
    "observations/third_party_scripts.json",
    "observations/robots_observations.json",
)


def _load(relative: str) -> Any:
    path = DATASET_DIR / relative
    if not path.is_file():
        return None
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def _observations(document: Any) -> list[dict[str, Any]]:
    if isinstance(document, dict):
        values = document.get("observations", [])
    elif isinstance(document, list):
        values = document
    else:
        return []
    if not isinstance(values, list):
        return []
    return [item for item in values if isinstance(item, dict)]


def _host(record: dict[str, Any]) -> str:
    for key in ("hostname", "site_hostname", "url", "robots_url"):
        value = record.get(key)
        if not isinstance(value, str) or not value.strip():
            continue
        candidate = value.strip().lower().rstrip(".")
        if "://" in candidate:
            candidate = (urlparse(candidate).hostname or "").lower().rstrip(".")
        if candidate:
            return candidate
    return ""


def _join(values: Any) -> str:
    if isinstance(values, list):
        return ";".join(sorted(str(value) for value in values if value not in (None, "")))
    if values in (None, ""):
        return ""
    return str(values)


def _apex(hostname: str) -> str:
    labels = hostname.split(".")
    if len(labels) <= 3:
        return hostname
    return ".".join(labels[-3:])


def _subdomain(hostname: str) -> str:
    labels = hostname.split(".")
    if len(labels) <= 3:
        return ""
    return ".".join(labels[:-3])


def write_csv_gz(path: Path, header: list[str], rows: Iterable[Iterable[Any]]) -> dict[str, Any]:
    """Write a deterministic gzipped CSV and return its fingerprint."""
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(header)
    count = 0
    for row in rows:
        writer.writerow(["" if value is None else value for value in row])
        count += 1
    payload = buffer.getvalue().encode("utf-8")
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("wb") as handle:
        with gzip.GzipFile(filename="", mode="wb", fileobj=handle, mtime=0) as archive:
            archive.write(payload)
    return {
        "rows": count,
        "bytes": path.stat().st_size,
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
    }


def _json_fingerprint(path: Path) -> dict[str, Any]:
    return {
        "bytes": path.stat().st_size,
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
    }


def build_roster() -> dict[str, Any]:
    roster = _load("roster.json") or []
    rows = [
        (
            record.get("province_id"),
            record.get("province"),
            record.get("district_id"),
            record.get("district"),
            record.get("municipality_id"),
            record.get("name"),
            record.get("normalized_name"),
        )
        for record in roster
        if isinstance(record, dict)
    ]
    header = [
        "province_id",
        "province",
        "district_id",
        "district",
        "municipality_id",
        "name",
        "normalized_name",
    ]
    return write_csv_gz(DATASET_DIR / "roster.csv.gz", header, rows)


def build_sites() -> dict[str, Any]:
    sample = _load("tls_sample.json") or {}
    sampled = {str(host).lower().rstrip(".") for host in sample.get("hostnames", []) if isinstance(host, str)}
    attribution = _load("attribution.json") or {}
    attributed = {
        str(record.get("hostname")).lower().rstrip(".")
        for record in attribution.get("records", [])
        if isinstance(record, dict) and record.get("hostname")
    }
    crtsh = _load("sources/crtsh_gov_np.json") or []
    discovered: Counter = Counter()
    for record in crtsh:
        if not isinstance(record, dict):
            continue
        for field in ("name_value", "common_name"):
            value = record.get(field)
            if not isinstance(value, str):
                continue
            for candidate in value.splitlines():
                candidate = candidate.strip().lower().rstrip(".")
                if candidate.startswith("*."):
                    candidate = candidate[2:]
                if not candidate.endswith(".gov.np") or "/" in candidate:
                    continue
                discovered[candidate] += 1
    for host in sampled:
        discovered.setdefault(host, 0)

    rows = []
    for hostname in sorted(discovered.keys() | attributed):
        sources = []
        if discovered.get(hostname):
            sources.append("crtsh")
        if hostname in sampled:
            sources.append("tls_sample")
        if hostname in attributed:
            sources.append("attribution")
        rows.append(
            (
                hostname,
                _apex(hostname),
                _subdomain(hostname),
                "true" if hostname in sampled else "false",
                "+".join(sources) if sources else "unknown",
            )
        )
    header = ["hostname", "apex_hostname", "subdomain", "in_observed_sample", "discovered_via"]
    return write_csv_gz(DATASET_DIR / "sites.csv.gz", header, rows)


def build_attribution() -> dict[str, Any]:
    document = _load("attribution.json") or {}
    records = document.get("records", []) if isinstance(document, dict) else []
    unresolved = document.get("unresolved", []) if isinstance(document, dict) else []
    rows = []
    for record in list(records) + list(unresolved):
        if not isinstance(record, dict):
            continue
        rows.append(
            (
                record.get("hostname") or "",
                record.get("local_level_id"),
                record.get("local_level_name"),
                record.get("district"),
                record.get("province"),
                record.get("method"),
                record.get("confidence"),
                record.get("status") or ("mapped" if record.get("hostname") else "unresolved"),
                record.get("evidence_url"),
                record.get("evidence_note"),
                record.get("decided_at"),
            )
        )
    header = [
        "hostname",
        "local_level_id",
        "local_level_name",
        "district",
        "province",
        "method",
        "confidence",
        "status",
        "evidence_url",
        "evidence_note",
        "decided_at",
    ]
    rows.sort(key=lambda row: (str(row[1]), str(row[0])))
    return write_csv_gz(DATASET_DIR / "attribution.csv.gz", header, rows)


def build_hosting() -> dict[str, Any]:
    records = _observations(_load("observations/hosting_observations.json"))
    rows = []
    for record in records:
        rows.append(
            (
                _host(record),
                _join(record.get("ip_addresses")),
                _join(record.get("asn")),
                _join(record.get("organization")),
                _join(record.get("country")),
                _join(record.get("country_codes")),
                record.get("hosting_classification"),
                record.get("confidence"),
                record.get("status"),
                record.get("observed_at"),
                record.get("error"),
            )
        )
    header = [
        "hostname",
        "ip_addresses",
        "asn",
        "organization",
        "countries",
        "country_codes",
        "hosting_classification",
        "confidence",
        "status",
        "observed_at",
        "error",
    ]
    rows.sort(key=lambda row: str(row[0]))
    return write_csv_gz(DATASET_DIR / "hosting.csv.gz", header, rows)


def build_dns_mail() -> dict[str, Any]:
    records = _observations(_load("observations/dns_mail_observations.json"))
    rows = []
    for record in records:
        dns = record.get("dns_records") if isinstance(record.get("dns_records"), dict) else {}
        mail = record.get("mail_security") if isinstance(record.get("mail_security"), dict) else {}
        spf = mail.get("spf") if isinstance(mail.get("spf"), dict) else {}
        dmarc = mail.get("dmarc") if isinstance(mail.get("dmarc"), dict) else {}
        rows.append(
            (
                _host(record),
                len(dns.get("A") or []),
                len(dns.get("AAAA") or []),
                len(dns.get("MX") or []),
                len(dns.get("NS") or []),
                len(dns.get("CAA") or []),
                len(dns.get("TXT") or []),
                "true" if mail.get("mx_present") else "false",
                spf.get("status"),
                dmarc.get("status"),
                dmarc.get("policy"),
                record.get("status"),
                record.get("confidence"),
                record.get("observed_at"),
            )
        )
    header = [
        "hostname",
        "a_count",
        "aaaa_count",
        "mx_count",
        "ns_count",
        "caa_count",
        "txt_count",
        "mx_present",
        "spf_status",
        "dmarc_status",
        "dmarc_policy",
        "status",
        "confidence",
        "observed_at",
    ]
    rows.sort(key=lambda row: str(row[0]))
    return write_csv_gz(DATASET_DIR / "dns_mail.csv.gz", header, rows)


def build_http_headers() -> dict[str, Any]:
    records = _observations(_load("observations/http_header_observations.json"))
    rows = []
    for record in records:
        headers = record.get("headers") if isinstance(record.get("headers"), dict) else {}
        normalized = {str(key).lower(): value for key, value in headers.items()}
        values: list[Any] = [_host(record), record.get("url"), record.get("final_url"), record.get("response_status")]
        present = 0
        for name in HEADER_NAMES:
            value = normalized.get(name.lower())
            has = isinstance(value, str) and bool(value.strip())
            present += int(has)
            values.append("true" if has else "false")
        values.extend(
            [
                len(HEADER_NAMES) - present,
                record.get("status"),
                record.get("error"),
                record.get("timestamp") or record.get("observed_at"),
            ]
        )
        rows.append(tuple(values))
    header = [
        "hostname",
        "url",
        "final_url",
        "response_status",
        *[HEADER_COLUMNS[name] for name in HEADER_NAMES],
        "missing_header_count",
        "status",
        "error",
        "observed_at",
    ]
    rows.sort(key=lambda row: str(row[0]))
    return write_csv_gz(DATASET_DIR / "http_headers.csv.gz", header, rows)


def build_tls() -> dict[str, Any]:
    records = _observations(_load("observations/tls_observations.json"))
    rows = []
    for record in records:
        cipher = record.get("cipher") if isinstance(record.get("cipher"), dict) else {}
        rows.append(
            (
                _host(record),
                record.get("status"),
                record.get("validity"),
                record.get("issuer"),
                record.get("subject"),
                record.get("valid_from"),
                record.get("expiration"),
                record.get("protocol"),
                cipher.get("name"),
                record.get("certificate_sha256"),
                record.get("observed_at"),
                record.get("error"),
            )
        )
    header = [
        "hostname",
        "status",
        "validity",
        "issuer",
        "subject",
        "valid_from",
        "expiration",
        "protocol",
        "cipher_name",
        "certificate_sha256",
        "observed_at",
        "error",
    ]
    rows.sort(key=lambda row: str(row[0]))
    return write_csv_gz(DATASET_DIR / "tls.csv.gz", header, rows)


def build_third_party() -> dict[str, Any]:
    records = _observations(_load("observations/third_party_scripts.json"))
    rows = []
    for record in records:
        hostname = _host(record)
        scripts = record.get("scripts") if isinstance(record.get("scripts"), list) else []
        if not scripts:
            rows.append(
                (
                    hostname,
                    "",
                    "",
                    "",
                    "",
                    record.get("script_count", 0),
                    record.get("third_party_script_count", 0),
                    record.get("status"),
                    record.get("observed_at"),
                )
            )
            continue
        for script in scripts:
            if not isinstance(script, dict):
                continue
            rows.append(
                (
                    hostname,
                    script.get("url"),
                    script.get("hostname"),
                    script.get("category"),
                    script.get("confidence"),
                    record.get("script_count"),
                    record.get("third_party_script_count"),
                    record.get("status"),
                    record.get("observed_at"),
                )
            )
    header = [
        "hostname",
        "script_url",
        "script_hostname",
        "category",
        "confidence",
        "script_count",
        "third_party_script_count",
        "page_status",
        "observed_at",
    ]
    rows.sort(key=lambda row: (str(row[0]), str(row[1])))
    return write_csv_gz(DATASET_DIR / "third_party_scripts.csv.gz", header, rows)


def build_robots() -> dict[str, Any]:
    records = _observations(_load("observations/robots_observations.json"))
    rows = []
    for record in records:
        groups = record.get("directives") if isinstance(record.get("directives"), list) else []
        directive_count = sum(len(group.get("directives") or []) for group in groups if isinstance(group, dict))
        rows.append(
            (
                _host(record),
                "true" if record.get("accessible") else "false",
                record.get("status_code"),
                record.get("status"),
                len(groups),
                directive_count,
                record.get("final_url"),
                record.get("error"),
                record.get("observed_at"),
            )
        )
    header = [
        "hostname",
        "accessible",
        "status_code",
        "status",
        "group_count",
        "directive_count",
        "final_url",
        "error",
        "observed_at",
    ]
    rows.sort(key=lambda row: str(row[0]))
    return write_csv_gz(DATASET_DIR / "robots.csv.gz", header, rows)


def _revision() -> str | None:
    try:
        return subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=paths.REPO_ROOT,
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return None


def build() -> dict[str, Any]:
    files: dict[str, dict[str, Any]] = {}
    for name, builder in (
        ("sites.csv.gz", build_sites),
        ("roster.csv.gz", build_roster),
        ("attribution.csv.gz", build_attribution),
        ("hosting.csv.gz", build_hosting),
        ("dns_mail.csv.gz", build_dns_mail),
        ("http_headers.csv.gz", build_http_headers),
        ("tls.csv.gz", build_tls),
        ("third_party_scripts.csv.gz", build_third_party),
        ("robots.csv.gz", build_robots),
    ):
        files[name] = builder()

    for relative in RAW_ARTIFACTS:
        path = DATASET_DIR / relative
        if path.is_file():
            files[relative] = _json_fingerprint(path)

    report = DATASET_DIR / "audit_report.json"
    if report.is_file():
        files["audit_report.json"] = _json_fingerprint(report)

    info = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "git_revision": _revision(),
        "files": files,
    }
    (DATASET_DIR / "build.json").write_text(
        json.dumps(info, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    return info
